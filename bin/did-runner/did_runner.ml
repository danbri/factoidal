(* did:key resolution vector runner.

   Factoidal's first Decentralized Identifiers (DID) consumer. All
   did:key parsing/resolution logic lives in
   formal/fstar/DID.Key.fst (extracted to DID_Key.ml) — this file is
   I/O + comparison glue only (CLAUDE.md iron rule #11 / anti-pattern
   #15): find the vector fixtures under tests/did/, call
   DID_Key.did_key_document on each vector's did:key string, serialize
   the resulting triples with the F*-extracted
   RDF_NQuads_Serialize.nq_line_for_triple_default_graph (no hand-rolled
   RDF serialization here), and compare the resulting line SET against
   the vector's hand-transcribed expected N-Triples (see
   tests/did/README.md for exactly where each expected document came
   from and why — every one is transcribed from the did:key spec's own
   text, never generated by this project's own resolver, to avoid a
   circular "our code validates itself" test).

   A second self-contained section exercises DID_Key.parse_did_key's
   rejection paths (missing "did:key:" prefix, non-'z' multibase,
   wrong multicodec, empty string) against inputs that need no vendored
   fixture.

   Usage:
     ./did_runner                Run the default vector directory
     ./did_runner <dir>          Run vectors from a specific directory
     ./did_runner --help         Show this help
*)

(* ------------------------------------------------------------------ *)
(* Repo-root resolution (parallel to vc_runner.ml / jsonld_runner.ml). *)

let find_repo_root () =
  let rec walk d =
    if d = "/" || d = "" then None
    else if Sys.file_exists (Filename.concat d "CLAUDE.md") then Some d
    else walk (Filename.dirname d)
  in
  let start =
    try Filename.dirname (Sys.executable_name)
    with _ -> Sys.getcwd ()
  in
  match walk start with
  | Some r -> r
  | None ->
    (match walk (Sys.getcwd ()) with
     | Some r -> r
     | None -> Sys.getcwd ())

let vector_dir_candidates () =
  let repo_root = find_repo_root () in
  [ Filename.concat repo_root "tests/did";
    "tests/did";
    "../../tests/did";
    "../../../tests/did" ]

let default_vector_dir () =
  try List.find Sys.file_exists (vector_dir_candidates ())
  with Not_found -> Filename.concat (find_repo_root ()) "tests/did"

(* ------------------------------------------------------------------ *)
(* File I/O. *)

let read_file path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let s = Bytes.create n in
  really_input ic s 0 n;
  close_in ic;
  Bytes.to_string s

let read_lines_nonblank path =
  read_file path
  |> String.split_on_char '\n'
  |> List.map String.trim
  |> List.filter (fun l -> l <> "" && not (String.length l > 0 && l.[0] = '#'))

(* ------------------------------------------------------------------ *)
(* Vector discovery: every "<dir>/<name>.did" paired with "<dir>/<name>.nt". *)

let collect_vectors dir =
  match Sys.readdir dir with
  | exception Sys_error _ -> []
  | entries ->
    Array.to_list entries
    |> List.filter (fun n -> Filename.check_suffix n ".did")
    |> List.sort compare
    |> List.filter_map (fun name ->
      let base = Filename.remove_extension name in
      let did_path = Filename.concat dir name in
      let nt_path = Filename.concat dir (base ^ ".nt") in
      if Sys.file_exists nt_path then Some (base, did_path, nt_path) else None)

(* ------------------------------------------------------------------ *)
(* Resolution + comparison for one vector. *)

type outcome = Pass | Fail of string

let triple_lines (triples : RDF_Triple.triple list) : string list =
  List.map
    (fun t -> String.trim (RDF_NQuads_Serialize.nq_line_for_triple_default_graph t))
    triples

let run_vector (_name, did_path, nt_path) : outcome =
  let did_str = String.trim (read_file did_path) in
  let expected = List.sort compare (read_lines_nonblank nt_path) in
  match DID_Key.did_key_document did_str with
  | None -> Fail (Printf.sprintf "did_key_document returned None for %s" did_str)
  | Some triples ->
    let got = List.sort compare (triple_lines triples) in
    if got = expected then Pass
    else begin
      let only_in msgs xs ys =
        List.filter (fun x -> not (List.mem x ys)) xs
        |> List.map (fun x -> Printf.sprintf "  %s %s" msgs x)
      in
      let missing = only_in "MISSING (expected, not produced):" expected got in
      let extra = only_in "UNEXPECTED (produced, not expected):" got expected in
      Fail (String.concat "\n" (missing @ extra))
    end

(* ------------------------------------------------------------------ *)
(* parse_did_key rejection self-checks — no vendored fixture needed. *)

let rejection_cases : (string * string) list =
  [ "no did:key: prefix", "did:example:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK";
    "empty string", "";
    "did:key: with empty multibase value", "did:key:";
    "multibase not 'z' (base64url 'm')", "did:key:mAbCdEfGhIjKlMnOpQrStUvWxYz";
    (* secp256k1-pub (multicodec 0xe701), a genuine did:key value from the
       vendored w3c/did-test-suite fixtures — right multibase, wrong
       multicodec, so DID.Key (Ed25519-only) must reject it. *)
    "wrong multicodec (secp256k1)", "did:key:zQ3shokFTS3brHcDQrn82RUDfCZESWL1ZdCEJwekUDPQiYBme" ]

let run_rejection_case (label, input) : outcome =
  match DID_Key.parse_did_key input with
  | None -> Pass
  | Some _ -> Fail (Printf.sprintf "expected None for %s (%s), got Some" label input)

(* ------------------------------------------------------------------ *)
(* Main. *)

let print_help () =
  print_string
    "did:key resolution vector runner.\n\
     \n\
     Usage:\n\
     \  ./did_runner              Run the default vector directory (tests/did)\n\
     \  ./did_runner <dir>        Run vectors from a specific directory\n\
     \  ./did_runner --help       Show this help\n\
     \n\
     Resolves each <name>.did did:key string via the F*-extracted\n\
     DID_Key.did_key_document and compares the resulting RDF triples\n\
     (as sorted N-Triples lines) against <name>.nt. See\n\
     tests/did/README.md for vector provenance. Also runs\n\
     DID_Key.parse_did_key rejection self-checks (malformed inputs).\n"

let () =
  let args = Array.to_list Sys.argv |> List.tl in
  let dir = ref None in
  let rec loop = function
    | [] -> ()
    | ("--help" | "-h") :: _ -> print_help (); exit 0
    | p :: rest when !dir = None -> dir := Some p; loop rest
    | _ ->
      Printf.eprintf "did_runner: unexpected arguments; try --help\n";
      exit 2
  in
  loop args;
  let vector_dir = match !dir with Some p -> p | None -> default_vector_dir () in
  Printf.printf "=== did:key resolution vector runner ===\n";
  Printf.printf "Vector dir: %s\n\n" vector_dir;
  let vectors = collect_vectors vector_dir in
  if vectors = [] then begin
    Printf.eprintf "did_runner: no *.did/*.nt vector pairs found under %s\n" vector_dir;
    exit 2
  end;
  let vector_results =
    List.map (fun ((name, _, _) as v) ->
        let o = run_vector v in
        (match o with
         | Pass -> Printf.printf "  PASS: %s\n" name
         | Fail msg -> Printf.printf "  FAIL: %s\n%s\n" name msg);
        o)
      vectors
  in
  Printf.printf "\n";
  let rejection_results =
    List.map (fun ((label, _) as c) ->
        let o = run_rejection_case c in
        (match o with
         | Pass -> Printf.printf "  PASS: reject — %s\n" label
         | Fail msg -> Printf.printf "  FAIL: reject — %s\n    %s\n" label msg);
        o)
      rejection_cases
  in
  let all = vector_results @ rejection_results in
  let total = List.length all in
  let pass = List.length (List.filter (function Pass -> true | Fail _ -> false) all) in
  let fail = total - pass in
  Printf.printf "\n========================================\n";
  Printf.printf "did:key: %d pass, %d fail (out of %d)\n" pass fail total;
  Printf.printf "========================================\n";
  if fail > 0 then exit 1
